"""Regenerate the flash-only assets without a Node/Arduino dependency install."""
from pathlib import Path

root = Path(__file__).resolve().parent
html = (root / 'setup.html').read_text()
prefix, suffix = html.split('{{TOKEN}}')
middle, suffix = suffix.split('{{NAME}}')
interval, suffix = suffix.split('{{INTERVAL}}')
effective, suffix = suffix.split('{{EFFECTIVE}}')
default, suffix = suffix.split('{{DEFAULT}}')
assets = [('FormStart', prefix), ('FormMiddle', middle), ('FormInterval', interval),
          ('FormEffective', effective), ('FormDefault', default), ('FormEnd', suffix)]
for symbol, filename in [('Style', 'setup.css'), ('Script', 'setup.js')]:
    assets.append((symbol, (root / filename).read_text()))
out = ['// Generated by portal/generate-assets.py. Do not edit.', '#pragma once',
       '#include <pgmspace.h>', 'namespace portal_assets {']
for symbol, text in assets:
    assert ')PORTAL"' not in text
    out.append(f'static const char {symbol}[] PROGMEM = R"PORTAL({text})PORTAL";')
out.append('} // namespace portal_assets\n')
(root.parent / 'PortalAssets.h').write_text('\n'.join(out))
